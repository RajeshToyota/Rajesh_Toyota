#!/usr/bin/env python3
"""Load open orders from CTDMS "PO Order Listing" exports into bookings, creating the Sales Officers
and Team Leaders they name as employees (no login yet; linked by ctdms_name).

    python3 scripts/seed/build_ctdms_orders_seed.py --out data/private/ctdms_orders_seed.sql \
        <PO_Order_Listing.xls> [<more branch exports> ...]

Only orders whose CTDMS status is Booked or Accepted are loaded. The output contains customer and
staff names, so it is written under data/private/ (git-ignored) and applied directly to the
database, never committed. Re-running is safe: employees upsert on ctdms_name, bookings on branch +
CTDMS order number (order numbers repeat across dealer codes). Accepts .xls/.xlsx (converted with LibreOffice) or .csv.
"""

import argparse
import csv
import os
import re
import subprocess
import sys
import tempfile
import uuid
from collections import Counter, defaultdict

NS = uuid.UUID("6f1d7c1e-6f5b-4c55-9a5e-3c2c1f0b7a10")
OPEN_STATUSES = {"Booked", "Accepted"}
ROLE_TL = "00000000-0000-0000-0001-000000000005"
ROLE_SC = "00000000-0000-0000-0001-000000000006"
BUSINESS_HEAD = "00000000-0000-0000-0003-000000000002"
JAIPUR_OUTLET_HEAD = "00000000-0000-0000-0003-000000000003"


def uid(*parts):
    return str(uuid.uuid5(NS, "|".join(str(p) for p in parts)))


def q(v):
    if v is None or v == "":
        return "null"
    if isinstance(v, (int, float)):
        return str(int(v)) if float(v).is_integer() else repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def norm_name(s):
    return re.sub(r"\s+", " ", (s or "").strip().strip(".").strip())


def title(s):
    return " ".join(w.capitalize() if not re.fullmatch(r"[A-Z]-[A-Z]", w) else w for w in s.split())


def read_rows(path):
    if path.lower().endswith(".csv"):
        csv_path = path
    else:
        tmp = tempfile.mkdtemp()
        subprocess.run(["soffice", "--headless", "--convert-to", "csv", "--outdir", tmp, path],
                       check=True, capture_output=True)
        csv_path = os.path.join(tmp, os.path.splitext(os.path.basename(path))[0] + ".csv")
    rows = list(csv.reader(open(csv_path, encoding="utf-8", errors="replace")))
    hi = next(i for i, r in enumerate(rows) if "Order No" in r and "Order Status" in r)
    head = [h.strip() for h in rows[hi]]
    return [dict(zip(head, r)) for r in rows[hi + 1:] if len(r) > 5 and r[head.index("Order No")].startswith("ORD")]


def iso(d):
    dd, mm, yyyy = d.strip().split("/")
    return f"{yyyy}-{mm}-{dd}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("files", nargs="+")
    args = ap.parse_args()

    orders = []
    for f in args.files:
        orders += read_rows(f)
    skipped = Counter(o["Order Status"] for o in orders if o["Order Status"] not in OPEN_STATUSES)
    orders = [o for o in orders if o["Order Status"] in OPEN_STATUSES]

    # Staff: each person's branch is where most of their orders are; an SO reports to the TL most
    # often named on their orders.
    so_branch, tl_branch, so_tl = defaultdict(Counter), defaultdict(Counter), defaultdict(Counter)
    for o in orders:
        so, tl, dc = norm_name(o["Sales Officer"]), norm_name(o["Team Leader"]), o["Dealer Code"].strip()
        if so:
            so_branch[so][dc] += 1
            if tl:
                so_tl[so][tl] += 1
        if tl:
            tl_branch[tl][dc] += 1

    out = ["-- GENERATED by scripts/seed/build_ctdms_orders_seed.py — contains personal data, do not commit.",
           "begin;", ""]

    def emp(name, role, dealer_code, reports_to):
        return (f"insert into employees (id, name, role_id, outlet_id, reports_to_employee_id, ctdms_name) values ("
                f"{q(uid('emp', name.upper()))}, {q(title(name))}, {q(role)}, "
                f"(select id from outlets where ctdms_dealer_code = {q(dealer_code)}), {reports_to}, {q(name.upper())}) "
                f"on conflict (id) do update set outlet_id = excluded.outlet_id, role_id = excluded.role_id, "
                f"reports_to_employee_id = coalesce(employees.reports_to_employee_id, excluded.reports_to_employee_id);")

    out.append("-- Team Leaders (report to the branch's Outlet Head where one exists, else the Business Head)")
    for tl, c in sorted(tl_branch.items()):
        dc = c.most_common(1)[0][0]
        boss = q(JAIPUR_OUTLET_HEAD) if dc == "JP05A" else q(BUSINESS_HEAD)
        out.append(emp(tl, ROLE_TL, dc, boss))
    out.append("\n-- Sales Officers")
    for so, c in sorted(so_branch.items()):
        dc = c.most_common(1)[0][0]
        tl = so_tl[so].most_common(1)[0][0] if so_tl[so] else None
        boss = q(uid("emp", tl.upper())) if tl else (q(JAIPUR_OUTLET_HEAD) if dc == "JP05A" else q(BUSINESS_HEAD))
        out.append(emp(so, ROLE_SC, dc, boss))

    out.append("\n-- Open CTDMS orders (Booked / Accepted)")
    for o in orders:
        so = norm_name(o["Sales Officer"])
        amount = (o.get("Received Amount") or "").replace(",", "").strip() or None
        out.append(
            "insert into bookings (id, outlet_id, employee_id, ctdms_order_booking_no, ctdms_enquiry_no, ctdms_order_id, ctdms_order_date, "
            "ctdms_order_status, ctdms_customer_code, ctdms_icrop_enquiry_no, ctdms_suffix_code, ctdms_color_code, ctdms_sales_officer, "
            "ctdms_team_leader, customer_name, organization_name, institutional_group_type, received_amount, variant_id, color_id, "
            "imported_from_ctdms, status, created_at) values ("
            f"{q(uid('booking', o['Dealer Code'].strip(), o['Order No'].strip()))}, (select id from outlets where ctdms_dealer_code = {q(o['Dealer Code'].strip())}), "
            f"{q(uid('emp', so.upper())) if so else 'null'}, {q(o['Order No'].strip())}, null, {q(o['Order Id'].strip())}, "
            f"{q(iso(o['Order Date']))}, {q(o['Order Status'].strip())}, {q(o['Customer Code'].strip())}, {q(o['ICROP_ENQUIRY_NBR'].strip())}, "
            f"{q(o['Suffix Code'].strip())}, {q(o['Exterior Color Code'].strip())}, {q(so)}, {q(norm_name(o['Team Leader']))}, "
            f"{q(norm_name(o['Customer Name']))}, {q(norm_name(o['Organization Name']))}, {q(o['Institutional Group Type'].strip())}, "
            f"{amount or 'null'}, (select id from variants where tkm_suffix_code = {q(o['Suffix Code'].strip())}), "
            f"(select id from colors where tkm_color_code = {q(o['Exterior Color Code'].strip())}), true, 'booked', {q(iso(o['Order Date']))}::timestamptz) "
            "on conflict (outlet_id, ctdms_order_booking_no) where ctdms_order_booking_no is not null do update set "
            "ctdms_order_status = excluded.ctdms_order_status, received_amount = excluded.received_amount, "
            "variant_id = coalesce(bookings.variant_id, excluded.variant_id), color_id = coalesce(bookings.color_id, excluded.color_id), "
            "employee_id = coalesce(bookings.employee_id, excluded.employee_id);")
    out.append("\ncommit;")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(out) + "\n")

    by_branch = Counter((o["Dealer Code"].strip(), o["Order Status"]) for o in orders)
    print(f"orders={len(orders)} team_leaders={len(tl_branch)} sales_officers={len(so_branch)}")
    print("by branch/status:", dict(sorted(by_branch.items())))
    if skipped:
        print("skipped (not Booked/Accepted):", dict(skipped))
    codes = Counter(o["Suffix Code"].strip() for o in orders)
    print("distinct suffix codes:", len(codes), file=sys.stderr)


if __name__ == "__main__":
    main()
